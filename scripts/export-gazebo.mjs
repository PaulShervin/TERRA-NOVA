// Generates the Gazebo (gz-sim, SDF 1.9) assets of the ROS 2 package from the SAME data the web simulator uses:
//   worlds/industrial.sdf       boxes + cylinders from the layout colliders (identical to the JS LiDAR world), lights, ceiling
//   worlds/cave.sdf             full cave shell mesh (floor + walls + roof), lamps, dark ambient
//   worlds/cave_cutaway.sdf     same collision, but the roof triangles are left out of the visual mesh (what the cut-away view shows)
//   models/cave_shell*          OBJ meshes exported from the signed-distance field (surface nets) - ROS axes, metres
//   models/mapping_robot        differential-drive robot: 16-beam gpu_lidar, IMU, RGB camera (same sensor frames as the web robot)
//   config/*.json|bin           ground-truth free-space masks (coverage metric), spawn poses, cave formations (segmentation scoring)
// Usage: node scripts/export-gazebo.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { buildLayout } from '../src/layout/index.js';
import { buildColliders } from '../src/sensing/Colliders.js';
import { createOccupancyGrid, buildTruthFree } from '../src/mapping/OccupancyGrid.js';
import { buildCaveWorld, exportCaveJSON } from '../src/cave/CaveGeometry.js';
import { LIDAR } from '../src/sensing/Lidar.js';
import { ROBOT_SCALE, SENSOR_FRAMES } from '../src/Robot.js';

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../gazebo/ros2_ws/src/mining_sim_gz');
const out = (rel, text) => { const p = path.join(PKG, rel); mkdirSync(path.dirname(p), { recursive: true }); writeFileSync(p, text); return p; };
const f = (v) => Number(v.toFixed(4));

// ------------------------------------------------------------------------------------------------ materials
const PALETTE = {
  wall: '0.62 0.62 0.60', pillar: '0.50 0.50 0.50', container: '0.25 0.45 0.30', storage: '0.55 0.40 0.22', rack: '0.85 0.45 0.10', obstacle: '0.35 0.30 0.25',
  equipment: '0.15 0.35 0.65', barrier: '0.85 0.85 0.85', platform: '0.45 0.47 0.50', pipe: '0.75 0.15 0.12', machinery: '0.20 0.35 0.65', fence: '0.30 0.30 0.30',
  floor: '0.36 0.36 0.35', ceiling: '0.25 0.25 0.26',
};
const material = (rgb) => `<material><ambient>${rgb} 1</ambient><diffuse>${rgb} 1</diffuse><specular>0.05 0.05 0.05 1</specular></material>`;

const header = (name, { sun, ambient, background }) => `<?xml version="1.0" ?>
<!-- GENERATED by scripts/export-gazebo.mjs - do not edit by hand -->
<sdf version="1.9">
  <world name="${name}">
    <physics name="default_physics" type="ode"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <gravity>0 0 -9.81</gravity>
    <scene><ambient>${ambient}</ambient><background>${background}</background><shadows>true</shadows></scene>
${sun ? `    <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 30 0 0 0</pose><diffuse>0.8 0.8 0.78 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.4 0.2 -0.9</direction></light>\n` : ''}`;

const pointLight = (name, [x, y, z], { range = 25, diffuse = '1 0.93 0.8 1', shadows = false } = {}) =>
  `    <light type="point" name="${name}"><pose>${f(x)} ${f(y)} ${f(z)} 0 0 0</pose><diffuse>${diffuse}</diffuse><specular>0.1 0.1 0.1 1</specular><cast_shadows>${shadows}</cast_shadows>` +
  `<attenuation><range>${range}</range><constant>0.4</constant><linear>0.05</linear><quadratic>0.005</quadratic></attenuation></light>\n`;

// ------------------------------------------------------------------------------------------------ truth masks
function writeMask(name, grid, truth, count, extra = {}) {
  out(`config/${name}.bin`, Buffer.from(truth));
  out(`config/${name}.json`, JSON.stringify({ file: `${name}.bin`, layout: 'row-major [j*W+i], uint8, 1 = reachable free space', res: grid.res, W: grid.W, H: grid.H, count, ...extra }, null, 2));
}

// ================================================================================================ INDUSTRIAL
function exportIndustrial() {
  const layout = buildLayout();
  const world = buildColliders(layout);
  const b = world.bounds;
  let sdf = header('industrial', { sun: true, ambient: '0.45 0.45 0.45 1', background: '0.55 0.62 0.70 1' });
  layout.lights.forEach((p, i) => { sdf += pointLight(`lamp_${i}`, p, { range: 30 }); });
  sdf += '    <model name="facility"><static>true</static>\n';
  const slab = (id, cat, cx, cy, z0, z1, sx, sy) => `      <link name="${id}"><pose>${f(cx)} ${f(cy)} ${f((z0 + z1) / 2)} 0 0 0</pose>`
    + `<collision name="c"><geometry><box><size>${f(sx)} ${f(sy)} ${f(z1 - z0)}</size></box></geometry></collision>`
    + `<visual name="v"><geometry><box><size>${f(sx)} ${f(sy)} ${f(z1 - z0)}</size></box></geometry>${material(PALETTE[cat])}</visual></link>\n`;
  sdf += slab('floor', 'floor', (b.xMin + b.xMax) / 2, (b.yMin + b.yMax) / 2, -0.2, 0, b.xMax - b.xMin + 2, b.yMax - b.yMin + 2);
  sdf += slab('ceiling', 'ceiling', (b.xMin + b.xMax) / 2, (b.yMin + b.yMax) / 2, world.ceilingZ, world.ceilingZ + 0.2, b.xMax - b.xMin + 2, b.yMax - b.yMin + 2);
  let n = 0;
  for (const it of world.items) {
    const rgb = PALETTE[it.cat] ?? '0.5 0.5 0.5', h = it.z1 - it.z0;
    if (it.t === 'b') {
      const yaw = Math.atan2(it.s, it.c);
      sdf += `      <link name="${it.id}_${n++}"><pose>${f(it.cx)} ${f(it.cy)} ${f(it.z0 + h / 2)} 0 0 ${f(yaw)}</pose>`
        + `<collision name="c"><geometry><box><size>${f(it.hx * 2)} ${f(it.hy * 2)} ${f(h)}</size></box></geometry></collision>`
        + `<visual name="v"><geometry><box><size>${f(it.hx * 2)} ${f(it.hy * 2)} ${f(h)}</size></box></geometry>${material(rgb)}</visual></link>\n`;
    } else {
      sdf += `      <link name="${it.id}_${n++}"><pose>${f(it.cx)} ${f(it.cy)} ${f(it.z0 + h / 2)} 0 0 0</pose>`
        + `<collision name="c"><geometry><cylinder><radius>${f(it.r)}</radius><length>${f(h)}</length></cylinder></geometry></collision>`
        + `<visual name="v"><geometry><cylinder><radius>${f(it.r)}</radius><length>${f(h)}</length></cylinder></geometry>${material(rgb)}</visual></link>\n`;
    }
  }
  sdf += '    </model>\n  </world>\n</sdf>\n';
  out('worlds/industrial.sdf', sdf);

  const grid = createOccupancyGrid(b, 0.2);
  const t = buildTruthFree(grid, world);
  writeMask('truth_industrial', grid, t.truth ?? t, t.count ?? 0, { bounds: b });
  out('config/industrial_info.json', JSON.stringify({ spawn: [-16, -6, 0.05], yaw: 0, bounds: b, ceilingZ: world.ceilingZ }, null, 2));
  console.log(`industrial.sdf: ${world.items.length} colliders, ${layout.lights.length} lights`);
}

// ================================================================================================ CAVE
function writeObj(name, mesh, skipRoof) {
  const { positions, normals, indices } = mesh;
  const lines = ['# GENERATED by scripts/export-gazebo.mjs: cave shell from a signed-distance field (ROS axes, metres, Z up)'];
  for (let i = 0; i < positions.length; i += 3) lines.push(`v ${f(positions[i])} ${f(positions[i + 1])} ${f(positions[i + 2])}`);
  for (let i = 0; i < normals.length; i += 3) lines.push(`vn ${f(normals[i])} ${f(normals[i + 1])} ${f(normals[i + 2])}`);
  let tris = 0;
  for (let t = 0; t < indices.length; t += 3) {
    const a = indices[t], b = indices[t + 1], c = indices[t + 2];
    const nz = (normals[a * 3 + 2] + normals[b * 3 + 2] + normals[c * 3 + 2]) / 3;
    if (skipRoof && nz < -0.3) continue; // same rule as the web viewer's roof toggle
    // surface nets winding is consistent with the field gradient; flip if needed so the face normal points into the air
    lines.push(`f ${a + 1}//${a + 1} ${b + 1}//${b + 1} ${c + 1}//${c + 1}`); tris++;
  }
  out(`models/${name}/meshes/${name}.obj`, lines.join('\n') + '\n');
  return tris;
}

const meshModel = (name, visualUri, collisionUri) => ({
  config: `<?xml version="1.0"?>\n<model><name>${name}</name><version>1.0</version><sdf version="1.9">model.sdf</sdf><description>Generated cave rock shell</description></model>\n`,
  sdf: `<?xml version="1.0" ?>\n<sdf version="1.9">\n  <model name="${name}"><static>true</static>\n    <link name="rock">\n`
    + `      <collision name="collision"><geometry><mesh><uri>${collisionUri}</uri></mesh></geometry><surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface></collision>\n`
    + `      <visual name="visual"><geometry><mesh><uri>${visualUri}</uri></mesh></geometry><material><ambient>0.30 0.24 0.18 1</ambient><diffuse>0.42 0.34 0.26 1</diffuse><specular>0.03 0.03 0.03 1</specular></material></visual>\n`
    + `    </link>\n  </model>\n</sdf>\n`,
});

function exportCave() {
  const world = buildCaveWorld({ withMesh: true });
  const full = writeObj('cave_shell', world.mesh, false);
  const cut = writeObj('cave_shell_cutaway', world.mesh, true);
  const fullModel = meshModel('cave_shell', 'model://cave_shell/meshes/cave_shell.obj', 'model://cave_shell/meshes/cave_shell.obj');
  out('models/cave_shell/model.config', fullModel.config); out('models/cave_shell/model.sdf', fullModel.sdf);
  const cutModel = meshModel('cave_shell_cutaway', 'model://cave_shell_cutaway/meshes/cave_shell_cutaway.obj', 'model://cave_shell/meshes/cave_shell.obj');
  out('models/cave_shell_cutaway/model.config', cutModel.config); out('models/cave_shell_cutaway/model.sdf', cutModel.sdf);

  const lamps = world.config.lamps.map(([x, y]) => { const l = world.network.locate(x, y); return [x, y, l.floor + l.height - 0.6]; });
  for (const [name, model] of [['cave', 'cave_shell'], ['cave_cutaway', 'cave_shell_cutaway']]) {
    let sdf = header(name, { sun: false, ambient: '0.06 0.055 0.05 1', background: '0.02 0.02 0.02 1' });
    lamps.forEach((p, i) => { sdf += pointLight(`lamp_${i}`, p, { range: 14, diffuse: '1 0.82 0.55 1' }); });
    sdf += `    <include><uri>model://${model}</uri><name>${model}</name></include>\n  </world>\n</sdf>\n`;
    out(`worlds/${name}.sdf`, sdf);
  }

  // ground-truth drivable mask on the 0.25 m exploration grid (same rule as CaveMapper)
  const grid = createOccupancyGrid(world.bounds, 0.25), fl = world.floor, t = new Uint8Array(grid.W * grid.H);
  let count = 0;
  for (let j = 0; j < grid.H; j++) for (let i = 0; i < grid.W; i++) {
    const [x, y] = grid.toWorld(i, j);
    const ci = Math.round((x - world.field.ox) / fl.voxel), cj = Math.round((y - world.field.oy) / fl.voxel);
    if (ci > 0 && cj > 0 && ci < fl.nx - 1 && cj < fl.ny - 1 && fl.drivable[cj * fl.nx + ci]) { t[grid.idx(i, j)] = 1; count++; }
  }
  writeMask('truth_cave', grid, t, count, { bounds: world.bounds });
  const sp = world.config.robot.spawn;
  const spawnZ = (world.floor.floorAt(sp[0], sp[1]) ?? 0) + 0.05;
  const data = exportCaveJSON(world);
  out('config/cave_info.json', JSON.stringify({ spawn: [sp[0], sp[1], f(spawnZ)], yaw: world.config.robot.yaw, bounds: world.bounds, formations: data.formations, landmarks: data.landmarks, lamps }, null, 2));
  console.log(`cave: ${world.mesh.positions.length / 3} vertices, ${full} triangles (full) / ${cut} (cut-away), ${lamps.length} lamps, ${count} drivable cells, spawn z ${f(spawnZ)}`);
}

// ================================================================================================ ROBOT
function exportRobot() {
  const s = ROBOT_SCALE, wr = 0.12 * s, track = 0.58 * s;
  const [, , lz] = SENSOR_FRAMES.lidar_link, [cx, , cz] = SENSOR_FRAMES.camera_link;
  const L = lz * s, C = [cx * s, cz * s], I = 0.3 * s;
  const az = (LIDAR.azStepDeg * Math.PI) / 180, samples = Math.round(360 / LIDAR.azStepDeg);
  const el = (LIDAR.elevMaxDeg * Math.PI) / 180;
  const inertia = (m, x, y, z) => `<inertial><mass>${m}</mass><inertia><ixx>${f((m / 12) * (y * y + z * z))}</ixx><iyy>${f((m / 12) * (x * x + z * z))}</iyy><izz>${f((m / 12) * (x * x + y * y))}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia></inertial>`;
  const wheel = (name, y) => `    <link name="${name}"><pose>0 ${f(y)} ${f(wr)} -1.5708 0 0</pose>${inertia(2, 0.3, 0.3, 0.1)}
      <collision name="c"><geometry><cylinder><radius>${f(wr)}</radius><length>0.08</length></cylinder></geometry><surface><friction><ode><mu>1.2</mu><mu2>1.2</mu2></ode></friction></surface></collision>
      <visual name="v"><geometry><cylinder><radius>${f(wr)}</radius><length>0.08</length></cylinder></geometry>${material('0.07 0.07 0.08')}</visual></link>
    <joint name="${name}_joint" type="revolute"><parent>base_link</parent><child>${name}</child><axis><xyz>0 0 1</xyz><limit><lower>-1e16</lower><upper>1e16</upper></limit></axis></joint>\n`;
  const caster = (name, x) => `    <link name="${name}"><pose>${f(x)} 0 0.07 0 0 0</pose>${inertia(0.5, 0.14, 0.14, 0.14)}
      <collision name="c"><geometry><sphere><radius>0.07</radius></sphere></geometry><surface><friction><ode><mu>0</mu><mu2>0</mu2></ode></friction></surface></collision>
      <visual name="v"><geometry><sphere><radius>0.07</radius></sphere></geometry>${material('0.1 0.1 0.1')}</visual></link>
    <joint name="${name}_joint" type="fixed"><parent>base_link</parent><child>${name}</child></joint>\n`;
  const mount = (name, [x, y, z], body) => `    <link name="${name}"><pose>${f(x)} ${f(y)} ${f(z)} 0 0 0</pose>${inertia(0.2, 0.05, 0.05, 0.05)}\n${body}    </link>\n    <joint name="${name}_joint" type="fixed"><parent>base_link</parent><child>${name}</child></joint>\n`;

  const sdf = `<?xml version="1.0" ?>
<!-- GENERATED by scripts/export-gazebo.mjs from the web robot (scale ${s}, sensor frames in src/Robot.js) -->
<sdf version="1.9">
  <model name="mapping_robot">
    <link name="base_link"><pose>0 0 0 0 0 0</pose>${inertia(45, 0.95, 0.68, 0.25)}
      <collision name="body_collision"><pose>0 0 ${f(0.22 * s)} 0 0 0</pose><geometry><box><size>${f(0.7 * s)} ${f(0.5 * s)} ${f(0.18 * s)}</size></box></geometry></collision>
      <visual name="body"><pose>0 0 ${f(0.22 * s)} 0 0 0</pose><geometry><box><size>${f(0.7 * s)} ${f(0.5 * s)} ${f(0.18 * s)}</size></box></geometry>${material('0.89 0.71 0.11')}</visual>
      <visual name="deck"><pose>${f(-0.05 * s)} 0 ${f(0.4 * s)} 0 0 0</pose><geometry><box><size>${f(0.5 * s)} ${f(0.36 * s)} ${f(0.1 * s)}</size></box></geometry>${material('0.95 0.42 0.13')}</visual>
      <visual name="mast"><pose>0 0 ${f(0.55 * s)} 0 0 0</pose><geometry><cylinder><radius>${f(0.035 * s)}</radius><length>${f(0.28 * s)}</length></cylinder></geometry>${material('0.12 0.14 0.16')}</visual>
    </link>
${wheel('left_wheel', track / 2)}${wheel('right_wheel', -track / 2)}${caster('caster_front', 0.3 * s)}${caster('caster_rear', -0.3 * s)}
${mount('lidar_link', [0, 0, L], `      <visual name="v"><geometry><cylinder><radius>0.06</radius><length>0.11</length></cylinder></geometry>${material('0.17 0.19 0.2')}</visual>
      <sensor name="lidar" type="gpu_lidar"><topic>/lidar</topic><gz_frame_id>lidar_link</gz_frame_id><update_rate>5</update_rate><always_on>true</always_on><visualize>false</visualize>
        <lidar>
          <scan>
            <horizontal><samples>${samples}</samples><resolution>1</resolution><min_angle>${f(-Math.PI)}</min_angle><max_angle>${f(Math.PI - az)}</max_angle></horizontal>
            <vertical><samples>${LIDAR.beams}</samples><resolution>1</resolution><min_angle>${f(-el)}</min_angle><max_angle>${f(el)}</max_angle></vertical>
          </scan>
          <range><min>${LIDAR.minRange}</min><max>${LIDAR.maxRange}</max><resolution>0.01</resolution></range>
          <noise><type>gaussian</type><mean>0</mean><stddev>${LIDAR.noiseSigma}</stddev></noise>
        </lidar>
      </sensor>\n`)}
${mount('imu_link', [0, 0, I], `      <sensor name="imu" type="imu"><topic>/imu</topic><gz_frame_id>imu_link</gz_frame_id><update_rate>100</update_rate><always_on>true</always_on>
        <imu><enable_orientation>true</enable_orientation><orientation_reference_frame><localization>ENU</localization></orientation_reference_frame>
          <angular_velocity><x><noise type="gaussian"><mean>0</mean><stddev>0.0009</stddev><bias_mean>0.0004</bias_mean><bias_stddev>0.0001</bias_stddev></noise></x><y><noise type="gaussian"><mean>0</mean><stddev>0.0009</stddev><bias_mean>0.0004</bias_mean><bias_stddev>0.0001</bias_stddev></noise></y><z><noise type="gaussian"><mean>0</mean><stddev>0.0009</stddev><bias_mean>0.0004</bias_mean><bias_stddev>0.0001</bias_stddev></noise></z></angular_velocity>
          <linear_acceleration><x><noise type="gaussian"><mean>0</mean><stddev>0.017</stddev></noise></x><y><noise type="gaussian"><mean>0</mean><stddev>0.017</stddev></noise></y><z><noise type="gaussian"><mean>0</mean><stddev>0.017</stddev></noise></z></linear_acceleration>
        </imu>
      </sensor>\n`)}
${mount('camera_link', [C[0], 0, C[1]], `      <visual name="v"><geometry><box><size>0.04 0.08 0.04</size></box></geometry>${material('0.04 0.1 0.2')}</visual>
      <sensor name="camera" type="camera"><topic>/camera/image_raw</topic><gz_frame_id>camera_link</gz_frame_id><update_rate>15</update_rate><always_on>true</always_on>
        <camera><horizontal_fov>1.2</horizontal_fov><image><width>640</width><height>480</height><format>R8G8B8</format></image><clip><near>0.1</near><far>40</far></clip></camera>
      </sensor>\n`)}
    <plugin filename="gz-sim-diff-drive-system" name="gz::sim::systems::DiffDrive">
      <left_joint>left_wheel_joint</left_joint><right_joint>right_wheel_joint</right_joint>
      <wheel_separation>${f(track)}</wheel_separation><wheel_radius>${f(wr)}</wheel_radius>
      <topic>/cmd_vel</topic><odom_topic>/odom</odom_topic><frame_id>odom</frame_id><child_frame_id>base_link</child_frame_id><odom_publish_frequency>20</odom_publish_frequency>
      <max_linear_velocity>1.5</max_linear_velocity><max_angular_velocity>2.5</max_angular_velocity>
      <max_linear_acceleration>2.0</max_linear_acceleration><max_angular_acceleration>4.0</max_angular_acceleration>
    </plugin>
    <plugin filename="gz-sim-odometry-publisher-system" name="gz::sim::systems::OdometryPublisher">
      <odom_frame>world</odom_frame><robot_base_frame>base_link</robot_base_frame><odom_topic>/ground_truth/odom</odom_topic><odom_publish_frequency>20</odom_publish_frequency><dimensions>3</dimensions>
    </plugin>
  </model>
</sdf>
`;
  out('models/mapping_robot/model.sdf', sdf);
  out('models/mapping_robot/model.config', '<?xml version="1.0"?>\n<model><name>mapping_robot</name><version>1.0</version><sdf version="1.9">model.sdf</sdf><description>Diff-drive robot: 16-beam gpu_lidar, IMU, RGB camera</description></model>\n');
  console.log(`mapping_robot: scale ${s}, lidar z ${f(L)} m, ${samples}x${LIDAR.beams} rays @5 Hz, wheel radius ${f(wr)} m, track ${f(track)} m`);
}

exportRobot();
